/* Насколько «сломан» кадр при данной коррупции */
function corruptionFx(c) {
  return {
    saturation: clampLocal(1 - c * 1.05, 0, 1),
    contrast: 1 + c * 0.18,
    vignette: 0.12 + c * 0.55,
    grain: c * 0.42,
    chroma: c * 3.4,          // px расхождения каналов (масштаб ×2)
    shakeIdle: c * 0.35,      // постоянная мелкая тряска
    detune: c * 45,           // расстройка звука в центах
  };
}
function clampLocal(v, a, b) { return v < a ? a : (v > b ? b : v); }

